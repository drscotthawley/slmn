def await_reply(dir:str, # parent dead-drop directory
                 session_id:str, # which session's outbox to wait on
                 prompt_id:str, # the id returned by drop_prompt
                 poll_interval:float=1.0 # seconds between mtime checks while waiting
                 ) -> dict: # {'id':..., 'path':..., 'files':...} -- see read_bundle
    "Block until a same-id reply bundle appears in a session's outbox/ (see reply_bundle) -- the bundle directory only appears once fully written (drop_bundle's atomic rename), so there's no risk of reading a partial reply -- then read and return it."
    outbox_dir = Path(_resolve_safe(dir)) / session_id / 'outbox' / prompt_id
    # since=0.0: we only care that outbox_dir gets *created* at all (_await_change's
    # exists-loop), not that it changes again afterward -- a rename-into-place directory
    # never gets touched a second time, so the default since=None (baseline = mtime at the
