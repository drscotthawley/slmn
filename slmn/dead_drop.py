def watch_session(dir:str, # parent dead-drop directory; a session-scoped inbox/received/outbox is created (or reused) under it
                   callback:callable, # called as callback(bundle) for each prompt bundle picked up (already moved to received/); bundle is the dict pickup_bundle() returns
                   poll_interval:float=1.0, # seconds between mtime checks while inbox/ is empty
                   max_iters:int=None, # stop after this many bundles-or-idle-checks (mainly for tests/scripted runs -- omit to run forever)
                   session_id:str=None # session id whose inbox/received/outbox to use; default auto-detects (see _session_id)
                   ) -> int:
    "Blocking loop, the bundle-aware sibling of watch(): repeatedly pickup_bundle()s prompt bundles from a session-scoped inbox/ subdirectory of `dir`, atomically moving each one to the matching received/ subdirectory (see pickup_bundle's move_to) before passing it to `callback` -- so a bundle sitting in received/ with no same-id bundle in outbox/ (see pending_replies) means it was seen but never answered, e.g. after a crash mid-processing. Also writes MACHINE_INFO.md into `dir` on first use, same as watch(). Runs forever unless `max_iters` is given. Returns the number of bundles processed."
    parent_ = Path(_resolve_safe(dir))
    parent_.mkdir(parents=True, exist_ok=True)
    _write_machine_info(parent_)
    session_dir = parent_ / (session_id or _session_id())
    inbox, received, outbox = session_dir / 'inbox', session_dir / 'received', session_dir / 'outbox'
    for d in (inbox, received, outbox, session_dir / 'completed'): d.mkdir(parents=True, exist_ok=True)
    n, iters = 0, 0
    while max_iters is None or iters < max_iters:
        base = inbox.stat().st_mtime
        b = pickup_bundle(str(inbox), move_to=str(received))
        if b is not None:
            callback(b)
            n += 1
        else:
            _await_change(str(inbox), poll_interval, since=base)
        iters += 1
    return n

