def _gpu_info() -> tuple:
    "GPU name(s) and total VRAM (in GB, one decimal place) via nvidia-smi, as two semicolon-joined strings, parallel across multiple GPUs -- ('none detected', 'none detected') if nvidia-smi isn't available or reports nothing."
    which = subprocess.run(['which', 'nvidia-smi'], capture_output=True, text=True).stdout.strip()
    if not which: return "none detected", "none detected"
    r = subprocess.run(['nvidia-smi', '--query-gpu=name,memory.total', '--format=csv,noheader,nounits'],
                        capture_output=True, text=True)
    rows = [l.strip() for l in r.stdout.strip().splitlines() if l.strip()]
    if r.returncode != 0 or not rows: return "none detected", "none detected"
    names, vrams = [], []
    for row in rows:
        name, mib = (p.strip() for p in row.rsplit(',', 1))
        names.append(name)
        vrams.append(f"{round(float(mib) / 1024, 1)} GB")
    return "; ".join(names), "; ".join(vrams)

