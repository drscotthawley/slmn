def drop_bundle(dir:str, # directory to drop the bundle into (created if it doesn't exist)
                 files:dict, # {filename: content}, content str or bytes
                 bundle_id:str=None # bundle directory name; auto-generated (see _prompt_id) from the first str-valued file's content if omitted
                 ) -> str: # path to the bundle directory
    "Atomically drop a multi-file bundle -- e.g. a prompt's text plus an image attachment -- as a single directory under `dir`. Writes every file into a hidden temp directory first, then atomically renames the whole directory into place (extends drop()'s Maildir trick to a whole bundle), so a concurrent pickup/watch never sees a partially-written bundle. Returns the bundle's final directory path."
    dir_ = Path(_resolve_safe(dir))
    dir_.mkdir(parents=True, exist_ok=True)
    if bundle_id is None:
        text = next((v for v in files.values() if isinstance(v, str)), "")
        bundle_id = _prompt_id(text)
    tmp = dir_ / f".tmp-{uuid.uuid4().hex}"
    tmp.mkdir()
    for fname, content in files.items():
        if isinstance(content, bytes): (tmp / fname).write_bytes(content)
        else: (tmp / fname).write_text(content)
    final = dir_ / bundle_id
    tmp.rename(final)
    return str(final)

def read_bundle(path:str # a bundle directory, as written by drop_bundle
                 ) -> dict: # {filename: content}, text decoded where possible, else raw bytes
    "Read every file in a bundle directory into {filename: content}, decoding as text where possible and falling back to raw bytes for anything that isn't (e.g. an image attachment)."
    dir_ = Path(path)
    files = {}
    for f in sorted(dir_.iterdir()):
        if not f.is_file() or f.name.startswith('.'): continue
        try: files[f.name] = f.read_text()
        except UnicodeDecodeError: files[f.name] = f.read_bytes()
    return files

def pickup_bundle(dir:str, # directory to check for bundles
                   move_to:str=None # if given, the bundle directory is atomically moved here (same name) instead of being deleted -- e.g. inbox -> received
                   ) -> dict: # {'id':..., 'path':..., 'files':...}, or None if nothing's pending
    "Look for the oldest pending bundle directory in `dir` (sorted by name, so timestamp-led bundle ids -- see _prompt_id -- come out in creation order) and read it (see read_bundle). Returns None if `dir` doesn't exist or has no bundles. If `move_to` is given, atomically renames the bundle directory there instead of deleting it -- marking it claimed without discarding it."
    dir_ = Path(_resolve_safe(dir))
    if not dir_.exists(): return None
    candidates = sorted(p for p in dir_.iterdir() if p.is_dir() and not p.name.startswith('.'))
    if not candidates: return None
    bundle_dir = candidates[0]
    files = read_bundle(bundle_dir)
    path = str(bundle_dir)
    if move_to:
        move_dir = Path(_resolve_safe(move_to))
        move_dir.mkdir(parents=True, exist_ok=True)
        dest = move_dir / bundle_dir.name
        bundle_dir.rename(dest)
        path = str(dest)
    else:
        shutil.rmtree(bundle_dir)
    return {'id': bundle_dir.name, 'path': path, 'files': files}

