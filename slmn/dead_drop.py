def _prompt_id(text:str="" # representative text to derive the human-readable slug from (e.g. the prompt itself); safe to omit
                ) -> str:
    "Generate a bundle id: `{timestamp}-{slug}-{rand}`. The timestamp leads so bundle directories still sort chronologically (same reasoning as drop()'s default filename); `slug` is the first 6 lowercase alnum characters that survive stripping everything else out of `text` (falls back to 'prompt' if nothing survives, e.g. text that's empty or all-emoji) for a human-skimmable `ls`; `rand` is a short hex suffix (uuid4, same convention as drop()'s default filename) disambiguating same-second collisions."
